use std::collections::BTreeMap;
use std::{env, fmt::Write as _, fs, path::PathBuf};

#[derive(Default)]
struct Node {
    children: BTreeMap<u8, u16>,
    rank: u16, // rank + 1, or zero for an internal node
}

fn index(n: usize) -> u16 {
    u16::try_from(n).expect("v1 tables must fit 16-bit offsets")
}

fn main() {
    println!("cargo:rerun-if-changed=data/vocab.txt");
    let dir = PathBuf::from(env::var_os("OUT_DIR").unwrap());
    let source = fs::read_to_string("data/vocab.txt").unwrap();
    let mut prefix = vec![0u16; 65536];
    let mut nodes = vec![Node::default()]; // zero means missing
    let mut offsets = vec![0u16];
    let mut data = Vec::new();
    let mut fingerprint = 0x811c9dc5u32;
    for (rank, line) in source.lines().enumerate() {
        assert!(line.len() % 2 == 0 && line.is_ascii());
        let word: Vec<u8> = (0..line.len())
            .step_by(2)
            .map(|i| u8::from_str_radix(&line[i..i + 2], 16).unwrap())
            .collect();
        assert!((3..=32).contains(&word.len()) && std::str::from_utf8(&word).is_ok());
        for &byte in std::iter::once(&(word.len() as u8)).chain(&word) {
            fingerprint = (fingerprint ^ u32::from(byte)).wrapping_mul(0x01000193);
        }
        data.extend_from_slice(&word);
        offsets.push(index(data.len()));

        let head = usize::from(u16::from_be_bytes([word[0], word[1]]));
        if prefix[head] == 0 {
            prefix[head] = index(nodes.len());
            nodes.push(Node::default());
        }
        let mut node = usize::from(prefix[head]);
        for &byte in &word[2..] {
            let next = if let Some(&next) = nodes[node].children.get(&byte) {
                next
            } else {
                let next = index(nodes.len());
                nodes[node].children.insert(byte, next);
                nodes.push(Node::default());
                next
            };
            node = usize::from(next);
        }
        assert_eq!(nodes[node].rank, 0, "duplicate piece");
        nodes[node].rank = index(rank + 1);
    }
    assert_eq!(offsets.len(), 4097);
    let mut edge_keys = Vec::new();
    let mut edge_targets = Vec::new();
    let mut starts = Vec::new();
    let mut degrees = Vec::new();
    let mut ranks = Vec::new();
    for node in nodes {
        starts.push(index(edge_keys.len()));
        degrees.push(u8::try_from(node.children.len()).unwrap());
        ranks.push(node.rank);
        for (key, target) in node.children {
            edge_keys.push(key);
            edge_targets.push(target);
        }
    }
    // Native-endian typed constants let the compiler use aligned table loads.
    // Compact each prefix row to its occupied span (first dimension = first byte).
    let mut row_base = vec![0u16; 256];
    let mut row_low = vec![0u8; 256];
    let mut row_len = vec![0u16; 256];
    let mut heads = Vec::new();
    for (i, row) in prefix.as_chunks::<256>().0.iter().enumerate() {
        if let Some(low) = row.iter().position(|&n| n != 0) {
            let high = row.iter().rposition(|&n| n != 0).unwrap();
            row_base[i] = index(heads.len());
            row_low[i] = low as u8;
            row_len[i] = index(high - low + 1);
            heads.extend_from_slice(&row[low..=high]);
        }
    }

    let mut tables = String::from("// Generated by build.rs\n");
    writeln!(
        tables,
        "pub const ID: [u8; 4] = {:?};",
        fingerprint.to_le_bytes()
    )
    .unwrap();
    macro_rules! table {
        ($name:ident, $ty:ty, $data:expr) => {
            writeln!(
                tables,
                "static {}: [{}; {}] = {:?};",
                stringify!($name),
                stringify!($ty),
                $data.len(),
                $data
            )
            .unwrap()
        };
    }
    table!(ROW_BASE, u16, row_base);
    table!(ROW_LOW, u8, row_low);
    table!(ROW_LEN, u16, row_len);
    table!(HEAD, u16, heads);
    table!(START, u16, starts);
    table!(DEGREE, u8, degrees);
    table!(RANK, u16, ranks);
    table!(KEY, u8, edge_keys);
    table!(TARGET, u16, edge_targets);
    // Reuse the word store as a native zstd raw dictionary. The most frequent
    // pieces sit closest to the start of the data being compressed.
    let mut history = Vec::with_capacity(data.len());
    for pair in offsets.windows(2).rev() {
        history.extend_from_slice(&data[usize::from(pair[0])..usize::from(pair[1])]);
    }
    for offset in &mut offsets {
        *offset = index(history.len()) - *offset;
    }
    table!(WORD_OFFSET, u16, offsets);
    fs::write(dir.join("words.bin"), history).unwrap();
    fs::write(dir.join("words.rs"), tables).unwrap();
}
